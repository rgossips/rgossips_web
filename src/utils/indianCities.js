// Convenience for the "match either direction" fuzzy search shared
// with list-influencers' Location filter and the campaign matcher.
export function matchesAnyCity(storedLocation, wantedCities) {
  const stored = String(storedLocation || "").toLowerCase();
  if (!stored) return false;
  return (wantedCities || []).some((c) => {
    const w = String(c || "").toLowerCase();
    return w && (stored.includes(w) || w.includes(stored));
  });
}
